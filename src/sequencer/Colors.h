#pragma once

// UI Colors
/// @brief Palette index used for active/highlighted UI elements.
#define UI_COLOR_ACTIVE                 0xf
/// @brief Palette index used for normal foreground UI elements.
#define UI_COLOR_NORMAL                 0xa
/// @brief Palette index used for secondary/dimmed UI elements.
#define UI_COLOR_DIM                    0x7
/// @brief Palette index used for strongly dimmed UI elements.
#define UI_COLOR_DIM_MORE               0x4
/// @brief Palette index used for footer backgrounds.
#define UI_COLOR_FOOTER_BACK            0x2
/// @brief Palette index used for inactive UI elements.
#define UI_COLOR_INACTIVE               0x2
/// @brief Palette index representing black/off pixels.
#define UI_COLOR_BLACK					0x0
